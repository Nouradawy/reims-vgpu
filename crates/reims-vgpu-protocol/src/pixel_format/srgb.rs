#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quantization_matches_the_srgb_transfer() {
        for step in 0..=65536 {
            let linear = f64::from(step) / 65536.0;
            let encoded = if linear <= 0.0031308 {
                12.92 * linear
            } else {
                1.055 * linear.powf(1.0 / 2.4) - 0.055
            };
            let expected = (encoded * 255.0 + 0.5) as u8;
            assert_eq!(encode_unorm8(linear), expected, "linear {linear}");
        }
        for value in [f64::NAN, f64::NEG_INFINITY, -1.0, 0.0] {
            assert_eq!(encode_unorm8(value), 0);
        }
        for value in [1.0, 2.0, f64::INFINITY] {
            assert_eq!(encode_unorm8(value), 255);
        }
    }
}
