//! Quantized sRGB transfer for CPU-published clear texels.
//!
//! Each threshold is the linear-light value at an encoded half-byte step:
//! e = (n + 0.5) / 255; l = e / 12.92 when e <= 0.04045,
//! otherwise l = ((e + 0.055) / 1.055)^2.4.
//! Searching these 255 boundaries performs the transfer and nearest-byte
//! quantization together, without a floating-point power dependency in no_std.
//! This applies only to RGB; alpha remains linear UNORM.

pub(super) fn encode_unorm8(linear: f64) -> u8 {
    if !matches!(linear.partial_cmp(&0.0), Some(core::cmp::Ordering::Greater)) {
        return 0;
    }
    if linear >= 1.0 {
        return 255;
    }
    LINEAR_THRESHOLDS.partition_point(|&threshold| linear >= threshold) as u8
}

